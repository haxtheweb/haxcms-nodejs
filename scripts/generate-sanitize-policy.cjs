/* global console, __dirname */
// Generates src/lib/haxcmsSanitizePolicy.json, the storage sanitizer policy
// shared with haxcms-php (system/backend/php/lib/haxcms-sanitize-policy.json).
// The tag lists start from the DOMPurify version installed here, so Node's
// DOMPurify backstop never needs to remove anything the policy keeps.
//
// usage: node scripts/generate-sanitize-policy.cjs
//        npx prettier --write src/lib/haxcmsSanitizePolicy.json
// then copy the file to haxcms-php.
const fs = require("fs");
const path = require("path");
const { JSDOM } = require("jsdom");

const root = path.join(__dirname, "..");
function buildPolicy() {
  const purify = fs.readFileSync(
    path.join(path.dirname(require.resolve("dompurify")), "purify.cjs.js"),
    "utf8",
  );
  function grabList(re) {
    const match = purify.match(re);
    if (!match) {
      throw new Error(`DOMPurify list not found: ${re}`);
    }
    return JSON.parse(
      `[${match[1].replace(/\s+/g, " ").replace(/,\s*$/, "")}]`,
    );
  }
  const purifyHtmlTags = grabList(/const html\$1 = freeze\(\[([\s\S]*?)\]\)/);
  const purifyForbidContents = grabList(
    /const DEFAULT_FORBID_CONTENTS = addToSet\(\{\}, \[([\s\S]*?)\]\)/,
  );

  // removed together with everything inside them
  const forbidden = [
    "script",
    "style",
    "svg",
    "math",
    "frame",
    "frameset",
    "applet",
    "meta",
    "link",
    "base",
    "noscript",
    "noembed",
    "noframes",
    "xmp",
    "plaintext",
    "title",
  ];
  const notInContent = new Set(["html", "head", "body"]);
  const allowed = purifyHtmlTags
    .filter((t) => !notInContent.has(t) && forbidden.indexOf(t) === -1)
    .concat(["iframe"])
    .sort();
  const removeWithContent = Array.from(
    new Set(
      forbidden.concat(
        purifyForbidContents.filter((t) => allowed.indexOf(t) === -1),
      ),
    ),
  ).sort();

  // names a browser exposes on document or on a form (DOM clobbering): the
  // properties of jsdom's Document and HTMLFormElement, plus browser-only ones
  const window = new JSDOM("<!doctype html><form></form>").window;
  const names = new Set();
  function collect(obj) {
    for (let o = obj; o; o = Object.getPrototypeOf(o)) {
      Object.getOwnPropertyNames(o).forEach((n) => names.add(n));
    }
  }
  collect(window.document);
  collect(window.document.querySelector("form"));
  [
    "adoptedStyleSheets",
    "browsingTopics",
    "featurePolicy",
    "fonts",
    "fragmentDirective",
    "fullscreenElement",
    "fullscreenEnabled",
    "hasPrivateToken",
    "hasRedemptionRecord",
    "permissionsPolicy",
    "pictureInPictureElement",
    "pictureInPictureEnabled",
    "pointerLockElement",
    "prerendering",
    "requestStorageAccess",
    "rootElement",
    "scrollingElement",
    "timeline",
    "wasDiscarded",
    "webkitHidden",
    "webkitVisibilityState",
    "xmlEncoding",
    "xmlStandalone",
    "xmlVersion",
  ].forEach((n) => names.add(n));
  window.close();

  const policy = {
    $comment:
      "HTML storage sanitizer policy shared by haxcms-nodejs (src/lib/haxcmsSanitizePolicy.json) and haxcms-php (system/backend/php/lib/haxcms-sanitize-policy.json); both must produce the same output. Generated by haxcms-nodejs scripts/generate-sanitize-policy.cjs.",
    version: 1,
    allowedTags: allowed,
    removeWithContent,
    customElementName: "^[a-z][a-z0-9._-]*-[a-z0-9._-]*$",
    reservedCustomElementNames: [
      "annotation-xml",
      "color-profile",
      "font-face",
      "font-face-format",
      "font-face-name",
      "font-face-src",
      "font-face-uri",
      "missing-glyph",
    ],
    attributeName: "^[a-z_:][a-z0-9_.:-]*$",
    forbiddenAttributes: ["srcdoc", "style", "is", "attributename", "xmlns"],
    unsafeAttributeValue:
      "(--!?|\\])>|<\\/(style|script|title|xmp|textarea|noscript|iframe|noembed|noframes)",
    clobberTags: [
      "button",
      "embed",
      "fieldset",
      "form",
      "iframe",
      "img",
      "input",
      "object",
      "output",
      "select",
      "textarea",
    ],
    clobberNames: Array.from(names)
      .filter((n) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(n))
      .sort(),
  };
  return policy;
}

if (require.main === module) {
  const policy = buildPolicy();
  fs.writeFileSync(
    path.join(root, "src/lib/haxcmsSanitizePolicy.json"),
    JSON.stringify(policy, null, 2) + "\n",
  );
  console.log(
    `allowed ${policy.allowedTags.length}, removeWithContent ${policy.removeWithContent.length}, clobberNames ${policy.clobberNames.length}`,
  );
}

module.exports = { buildPolicy };
