/* global process, console, __dirname */
// Writes src/lib/unicode-tables.json: the Unicode data the slug and search
// rules use, fixed at one Unicode version so haxcms-nodejs and haxcms-php
// give the same answer whatever their runtime's own Unicode tables are
// (haxtheweb/issues#3394). haxcms-php ships an identical copy as
// lib/unicode-tables.json. Regenerate with a Node.js whose
// process.versions.unicode is the version you want, then copy the file to
// haxcms-php and update the checksum both test suites pin.
"use strict";
const fs = require("fs");
const path = require("path");

function ranges(test) {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const inside =
      cp <= 0x10ffff &&
      !(cp >= 0xd800 && cp <= 0xdfff) &&
      test(String.fromCodePoint(cp));
    if (inside && start === -1) {
      start = cp;
    } else if (!inside && start !== -1) {
      out.push([start, cp - 1]);
      start = -1;
    }
  }
  return out;
}

const letterOrNumber = ranges((ch) => /[\p{L}\p{N}]/u.test(ch));
const searchKeepShort = ranges((ch) =>
  /[\p{N}\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Hangul}\p{Script=Thai}]/u.test(
    ch,
  ),
);
// for the one context rule toLowerCase applies: a capital sigma at the end
// of a word lowers to final sigma (U+03C2), anywhere else to U+03C3
const cased = ranges((ch) => /\p{Cased}/u.test(ch));
const caseIgnorable = ranges((ch) => /\p{Case_Ignorable}/u.test(ch));
const lower = {};
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) {
    continue;
  }
  const ch = String.fromCodePoint(cp);
  const lowered = ch.toLowerCase();
  if (lowered !== ch) {
    lower[cp] = lowered;
  }
}
const data = {
  about:
    "Unicode data for the slug and search rules, fixed at one version so both HAXcms backends agree (haxtheweb/issues#3394). Generated by haxcms-nodejs scripts/generate-unicode-tables.cjs; haxcms-php lib/unicode-tables.json is an identical copy.",
  unicode: process.versions.unicode,
  letterOrNumber,
  searchKeepShort,
  cased,
  caseIgnorable,
  lower,
};
const target = path.join(__dirname, "..", "src", "lib", "unicode-tables.json");
fs.writeFileSync(target, JSON.stringify(data) + "\n");
console.log(
  target,
  "unicode",
  data.unicode,
  "ranges",
  letterOrNumber.length,
  searchKeepShort.length,
  "cased",
  cased.length,
  caseIgnorable.length,
  "lower",
  Object.keys(lower).length,
);
